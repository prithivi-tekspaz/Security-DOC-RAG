//! Security documentation agent built on the Rig framework.
//! Uses a local Ollama server for embeddings (nomic-embed-text) and completion.
//! Usage: `cargo run -- <doc-type> <topic>`; writes `output/<type>-<topic>.md`.

#![forbid(unsafe_code)]

mod sections;

use anyhow::{Context, Result};
use rig::prelude::*;
use rig::{
    Embed, embeddings::EmbeddingsBuilder, loaders::PdfFileLoader,
    vector_store::in_memory_store::InMemoryVectorStore,
};
use sections::{DOC_TYPES, Section, find, slugify};
use serde::{Deserialize, Serialize};
use std::path::Path;

const PREAMBLE: &str = "You are a security documentation writer. Write for engineers, in Markdown. \
Use the retrieved context first. Fill gaps from your own knowledge and mark those lines `(model knowledge)`. \
Never invent CVE IDs, versions or commands. Write `needs review` when you are unsure. \
Output only the body of the requested section. Do not repeat the section title as a heading. Use ### for sub-headings. Do not link to documents that you were not given.";

#[derive(Embed, Clone, Debug, Serialize, Deserialize, Eq, PartialEq)]
struct Document {
    id: String,
    #[embed]
    content: String,
}

/// Splits text content into chunks of at most `chunk_size` characters along whitespace boundaries.
pub fn chunk_text(content: &str, chunk_size: usize) -> Vec<String> {
    let mut chunks = Vec::new();
    let mut current = String::new();
    for word in content.split_whitespace() {
        if current.len() + word.len() + 1 > chunk_size && !current.is_empty() {
            chunks.push(std::mem::take(&mut current).trim().to_string());
        }
        current.push_str(word);
        current.push(' ');
    }
    if !current.is_empty() {
        chunks.push(current.trim().to_string());
    }
    chunks
}

fn load_pdf(path: &Path) -> Result<Vec<String>> {
    const CHUNK_SIZE: usize = 2000;
    let content_chunks = PdfFileLoader::with_glob(path.to_str().context("Invalid path")?)?
        .read()
        .into_iter()
        .filter_map(|result| {
            result
                .map_err(|e| {
                    eprintln!("Error reading PDF content: {e}");
                    e
                })
                .ok()
        })
        .flat_map(|content| chunk_text(&content, CHUNK_SIZE))
        .collect::<Vec<_>>();
    if content_chunks.is_empty() {
        anyhow::bail!("No content found in PDF file: {}", path.display());
    }
    Ok(content_chunks)
}

/// Converts days since 1970-01-01 to a (year, month, day) civil date (proleptic Gregorian).
fn civil_from_days(days: i64) -> (i64, u32, u32) {
    let z = days + 719_468;
    let era = z.div_euclid(146_097);
    let doe = z.rem_euclid(146_097);
    let yoe = (doe - doe / 1_460 + doe / 36_524 - doe / 146_096) / 365;
    let doy = doe - (365 * yoe + yoe / 4 - yoe / 100);
    let mp = (5 * doy + 2) / 153;
    let d = (doy - (153 * mp + 2) / 5 + 1) as u32;
    let m = if mp < 10 { mp + 3 } else { mp - 9 } as u32;
    let y = yoe + era * 400 + i64::from(m <= 2);
    (y, m, d)
}

/// Formats a Unix timestamp (seconds) as a UTC `YYYY-MM-DD` date.
fn utc_date(unix_secs: u64) -> String {
    let (y, m, d) = civil_from_days((unix_secs / 86_400) as i64);
    format!("{y:04}-{m:02}-{d:02}")
}

fn today_utc() -> String {
    let secs = std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .map(|d| d.as_secs())
        .unwrap_or(0);
    utc_date(secs)
}

/// Assembles the final Markdown document from a header and generated `(title, body)` sections.
fn assemble(
    doc_title: &str,
    topic: &str,
    date: &str,
    model: &str,
    parts: &[(&str, String)],
) -> String {
    let mut out = format!(
        "# {doc_title}: {topic}\n\n- **Document type:** {doc_title}\n- **Topic:** {topic}\n- **Date:** {date}\n- **Model:** {model}\n\n> Draft generated by a local model. Human review required before use.\n"
    );
    for (title, body) in parts {
        out.push_str(&format!("\n## {title}\n\n{}\n", body.trim()));
    }
    out
}

fn section_prompt(doc_title: &str, topic: &str, s: &Section) -> String {
    format!(
        "Document type: {doc_title}\nTopic: {topic}\nSection: {}\nInstruction: {}\n\nWrite this section now.",
        s.title, s.instruction
    )
}

fn usage() -> ! {
    eprintln!("Usage: cargo run -- <doc-type> <topic>\nValid doc types:");
    for d in DOC_TYPES {
        eprintln!("  {:<24} {}", d.key, d.title);
    }
    std::process::exit(2);
}

/// Small built-in corpus used when `docs/` has no readable PDFs.
fn builtin_corpus() -> Vec<String> {
    vec![
        "OWASP Top 10: Broken Access Control allows users to act outside intended permissions.".to_string(),
        "SQL injection occurs when untrusted data is sent to an interpreter as part of a command.".to_string(),
        "Cross-site scripting (XSS) lets attackers inject client-side scripts into web pages.".to_string(),
        "Security misconfiguration is the most common vulnerability from insecure defaults.".to_string(),
        "Sensitive data exposure happens when data is not properly protected in transit or at rest.".to_string(),
    ]
}

#[tokio::main]
async fn main() -> Result<()> {
    let args: Vec<String> = std::env::args().skip(1).collect();
    let (doc, topic) = match args.as_slice() {
        [t, topic @ ..] if !topic.is_empty() => match find(t) {
            Some(d) => (d, topic.join(" ")),
            None => usage(),
        },
        _ => usage(),
    };

    let client = rig::providers::ollama::OllamaConfig::new()
        .with_base_url("http://localhost:11434")
        .client();

    let embed_model_name =
        std::env::var("EMBED_MODEL").unwrap_or_else(|_| "nomic-embed-text".to_string());
    let completion_model_name = std::env::var("COMPLETION_MODEL")
        .unwrap_or_else(|_| "CyberCrew/notmythos-8b:latest".to_string());

    let embedding_model = client.embedding(&embed_model_name, None).erase();

    // Load security documents from ./docs (PDF glob) if present.
    let docs_dir = std::env::current_dir()?.join("docs");
    let mut chunks: Vec<String> = Vec::new();
    if docs_dir.exists() {
        if let Ok(pdf_chunks) = load_pdf(&docs_dir.join("*.pdf")) {
            chunks.extend(pdf_chunks);
        }
    }
    if chunks.is_empty() {
        chunks = builtin_corpus();
    }
    println!("Loaded {} security chunks.", chunks.len());

    let mut builder = EmbeddingsBuilder::new(embedding_model.clone());
    for (i, chunk) in chunks.into_iter().enumerate() {
        builder = builder.document(Document {
            id: format!("security_doc_{i}"),
            content: chunk,
        })?;
    }
    let embeddings = builder.build().await?;
    println!("Successfully generated embeddings");

    let vector_store = InMemoryVectorStore::from_documents(embeddings);
    let index = vector_store.index(embedding_model);

    // `native_completion` (/api/chat) is required: the OpenAI-compatible `completion` refuses `options`.
    let agent = AgentBuilder::new(client.native_completion(&completion_model_name))
        .preamble(PREAMBLE)
        .dynamic_context(3, index)
        .temperature(0.35)
        .additional_params(rig::serde_json::json!({"options": {"num_ctx": 8192}}))
        .build();

    let total = doc.sections.len();
    let mut parts: Vec<(&str, String)> = Vec::with_capacity(total);
    for (i, s) in doc.sections.iter().enumerate() {
        let body = agent
            .prompt(section_prompt(doc.title, &topic, s))
            .await
            .with_context(|| format!("generating section '{}'", s.title))?;
        println!("[{}/{total}] {} ... done", i + 1, s.title);
        parts.push((s.title, body.to_string()));
    }

    let markdown = assemble(doc.title, &topic, &today_utc(), &completion_model_name, &parts);
    std::fs::create_dir_all("output")?;
    let path = format!("output/{}-{}.md", doc.key, slugify(&topic));
    std::fs::write(&path, markdown).with_context(|| format!("writing {path}"))?;
    println!("Saved {path}");
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_chunk_text_empty_string() {
        let chunks = chunk_text("", 100);
        assert!(chunks.is_empty());
    }

    #[test]
    fn test_chunk_text_whitespace_only() {
        let chunks = chunk_text("   \n\t   \r\n  ", 100);
        assert!(chunks.is_empty());
    }

    #[test]
    fn test_chunk_text_short_content() {
        let text = "OWASP Top 10: Broken Access Control.";
        let chunks = chunk_text(text, 100);
        assert_eq!(chunks.len(), 1);
        assert_eq!(chunks[0], text);
    }

    #[test]
    fn test_chunk_text_splits_at_word_boundary() {
        let words = vec!["vulnerability"; 20];
        let text = words.join(" ");
        // Each word is 13 chars + 1 space = 14 chars. Chunk size 50 fits 3 words (41 chars).
        let chunks = chunk_text(&text, 50);

        assert!(chunks.len() > 1);
        for chunk in &chunks {
            // No chunk should exceed the max chunk size unless a single word is larger
            assert!(chunk.len() <= 50, "Chunk exceeded size limit: {}", chunk.len());
            // No words should be split in half
            for word in chunk.split_whitespace() {
                assert_eq!(word, "vulnerability");
            }
        }
    }

    #[test]
    fn test_chunk_text_single_word_longer_than_chunk_size() {
        let long_token = "A".repeat(120);
        let chunks = chunk_text(&long_token, 50);
        // A single long token should still be captured rather than lost or panicking
        assert_eq!(chunks.len(), 1);
        assert_eq!(chunks[0], long_token);
    }

    #[test]
    fn test_chunk_text_retains_all_words() {
        let text = "SQL injection occurs when untrusted data is sent to an interpreter as part of a command or query.";
        let original_words: Vec<&str> = text.split_whitespace().collect();

        let chunks = chunk_text(text, 30);
        let reconstructed_words: Vec<&str> = chunks
            .iter()
            .flat_map(|c| c.split_whitespace())
            .collect();

        assert_eq!(original_words, reconstructed_words);
    }

    #[test]
    fn test_load_pdf_with_existing_docs() {
        let docs_dir = std::path::Path::new("docs");
        if docs_dir.exists() {
            let result = load_pdf(&docs_dir.join("*.pdf"));
            if let Ok(chunks) = result {
                assert!(!chunks.is_empty(), "Expected non-empty chunks from docs");
                for chunk in chunks {
                    assert!(!chunk.trim().is_empty());
                }
            }
        }
    }

    #[test]
    fn test_utc_date() {
        assert_eq!(utc_date(0), "1970-01-01");
        assert_eq!(utc_date(951_782_400), "2000-02-29");
        assert_eq!(utc_date(1_709_164_800), "2024-02-29");
        assert_eq!(utc_date(1_767_225_599), "2025-12-31");
        assert_eq!(utc_date(1_767_225_600), "2026-01-01");
    }

    #[test]
    fn test_assemble() {
        let parts = vec![
            ("Scope", "  Body one.\n".to_string()),
            ("Assets", "Body two.".to_string()),
        ];
        let md = assemble("Threat Model", "payment API", "2026-01-01", "m:latest", &parts);
        assert!(md.starts_with("# Threat Model: payment API\n"));
        assert!(md.contains("- **Date:** 2026-01-01"));
        assert!(md.contains("- **Model:** m:latest"));
        assert!(md.contains("\n## Scope\n\nBody one.\n"));
        assert!(md.find("## Scope").unwrap() < md.find("## Assets").unwrap());
    }
}
